import type { DialogueLine } from '../core/types';

// Визиты героев в лавку: у каждого героя маленькая история из трёх разговоров,
// которые открываются по одному за визит, а потом — короткие приветствия.
// После разговора герой предлагает сделку; её вид зависит от роли героя (см. engine.visitOffer):
//  • warrior   — «помогу с котлом»: бесплатный буст тапов (или критов) на минуту;
//  • herbalist — «подкормлю мастерские»: бесплатный буст дохода;
//  • merchant  — обмен: немного золота на эссенцию и ингредиенты;
//  • sage      — тренировка: эссенция в осколки этого героя.
// Спикеры в репликах: id героя, 'cat' (кот Ртуть), 'player', 'narrator'.

export interface HeroVisitText {
  /** Три разговора: знакомство → личное → доверие. 3–5 реплик в каждом. */
  arc: [DialogueLine[], DialogueLine[], DialogueLine[]];
  /** Реплики-приветствия для визитов после арки (одна фраза героя). */
  greet: string[];
  /** Как герой предлагает сделку своей роли (одна фраза героя). */
  offer: string;
  /** Ответ героя, если сделку приняли. */
  accept: string;
  /** Ответ героя, если отказались. */
  decline: string;
}

export const HERO_VISITS: Record<string, HeroVisitText> = {};
